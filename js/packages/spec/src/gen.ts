import type { RulesFile } from "./types.js";

/** Path of the canonical JSON file, relative to the spec root. */
export const SPEC_JSON = "generated/spec.json";

/** One case of spec.json: `path` is `<rule>/<case>` under fixtures/. */
export interface SpecJsonCase {
  path: string;
  case: unknown;
}

export const GEN_HEADER = "// Code generated by fldlint; DO NOT EDIT.";

/** Recursively sort object keys (arrays keep their order) for deterministic output. */
function canonical(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(canonical);
  if (v && typeof v === "object") {
    const o = v as Record<string, unknown>;
    return Object.fromEntries(Object.keys(o).sort().map((k) => [k, canonical(o[k])]));
  }
  return v;
}

/** Render the contents of rules.gen.ts for the given rules file. */
export function generateRulesTs(file: RulesFile): string {
  const skip = JSON.stringify(canonical(file.skipCategories), null, 2);
  const rules = JSON.stringify(file.rules.map(canonical), null, 2);
  return [
    GEN_HEADER,
    "",
    'import type { Rule, SkipCategory } from "./types.js";',
    "",
    `export const SPEC_VERSION = ${JSON.stringify(file.version)};`,
    "",
    `export const skipCategories: Readonly<Record<string, SkipCategory>> = ${skip};`,
    "",
    `export const rules: readonly Rule[] = ${rules};`,
    "",
  ].join("\n");
}

/**
 * Render spec/generated/spec.json: rules.yaml and every case.yaml as JSON,
 * cases sorted by path, source key order kept, 2-space indent, trailing newline.
 * Other languages read only this file and need no YAML parser.
 */
export function generateSpecJson(rules: RulesFile, cases: readonly SpecJsonCase[]): string {
  const sorted = [...cases].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  return `${JSON.stringify({ rules, cases: sorted }, null, 2)}\n`;
}
